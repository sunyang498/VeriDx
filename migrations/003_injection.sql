-- VeriDx schema v3 — P1.6 审查修订（审查 必13 存储型注入处置）
--
-- 为什么需要这一次迁移：
--   `questions.stem` 是**持久化**的不可信输入。一次投毒会永久生效：
--   所有做这道题的人都用同一段被写入的题干。所以至少要能**追溯来源**，
--   并显式标注"这是一段外部文本"。
--
-- 两条纪律（写在这里，防止以后被"优化"掉）：
--   1. 每次复用都重新过 L0/L1（**不得因为"上次跑过"就跳过**）。
--      本迁移只提供可视性，**不提供"已验证"标记** —— 那种标记正是存储型注入的入口。
--   2. `untrusted` 的默认值是 1（= 当成不可信）。默认 0 会让新写入的行
--      悄悄获得"可信"身份，而没人会记得去改它。
-- ============================================================================

-- ---------------------------------------------------------------------------
-- C-20  questions 补两列：来源与"是否外部文本"
-- 都可空/有安全默认值，因此无需表重建（`ALTER TABLE ADD COLUMN` 不破坏既有行）。
-- ---------------------------------------------------------------------------
ALTER TABLE questions ADD COLUMN untrusted INTEGER NOT NULL DEFAULT 1;
ALTER TABLE questions ADD COLUMN source_detail TEXT;

CREATE INDEX idx_questions_source ON questions(source);
